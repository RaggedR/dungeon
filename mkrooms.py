#!/usr/bin/env python3
"""Generate rooms.ts from THEME.md.  Room prose is the spec's own, unaltered."""
import re

md = open('THEME.md').read()

rooms = {}
for m in re.finditer(r'^\*\*(\d\.[A-F])\.\*\* (.+?)(?=\n\n)', md, re.S | re.M):
    rooms[m.group(1)] = ' '.join(m.group(2).split())

# The glossary is collected from the sixteen monsters' own CLAUDE.md files:
#   grep -h '^- \*\*[a-z...]*\*\* is ' monsters/*/CLAUDE.md | sort -u
GLOSS = {}
for line in __import__('subprocess').run(
        ["bash", "-c", r"grep -h '^- \*\*.*\*\* is ' monsters/*/CLAUDE.md | sort -u"],
        capture_output=True, text=True).stdout.splitlines():
    m = re.match(r'- \*\*(.+?)\*\* is (.+)$', line)
    if m:
        GLOSS[m.group(1)] = m.group(2)

# 0.A's five signs are chalked on the bench in front of the five things, in the
# order the bench sets them out; THEME.md gives them as a run of bold words.
ORDER_0A = ["im", "gi", "esir", "a", "na₄"]

signs = {}
for r, prose in rooms.items():
    if r == "0.A":
        signs[r] = ORDER_0A
        continue
    found, seen = [], set()
    for m in re.finditer(r'\*\*([^*]+)\*\*', prose):
        w = m.group(1).strip().rstrip('.')
        if w in GLOSS and w not in seen:
            seen.add(w)
            found.append(w)
    signs[r] = found

esc = lambda s: s.replace('\\', '\\\\').replace('"', '\\"')

out = ['''// rooms.ts — the room descriptions and the signs cut into their walls.
//
// GENERATED by `mkrooms.py`.  Do not hand-edit.
//
// Every description is THEME.md's own prose, unaltered.  The sign list for each
// room is the words THEME.md set in bold there that appear in the glossary, and
// the glossary is collected from the sixteen monsters' own CLAUDE.md files —
// which is where the meanings are authoritative, because a sign is meant to be
// read out to the player by a person and not printed by a program.

import type { Room } from "./spec.ts";

export const DESCRIPTION: Readonly<Record<Room, string>> = {''']
for r in sorted(rooms):
    out.append(f'  "{r}":\n    "{esc(rooms[r])}",')
out.append('};\n')
out.append('export const SIGNS: Readonly<Record<Room, readonly string[]>> = {')
for r in sorted(rooms):
    out.append(f'  "{r}": [' + ', '.join(f'"{w}"' for w in signs[r]) + '],')
out.append('};\n')
out.append('/** What each sign means.  An inhabitant reads these out; the program')
out.append(' *  holds them only so that an inhabitant can be asked. */')
out.append('export const GLOSS: Readonly<Record<string, string>> = {')
for k in sorted(GLOSS):
    out.append(f'  "{k}":\n    "{esc(GLOSS[k])}",')
out.append('};')

open('rooms.ts', 'w').write('\n'.join(out) + '\n')
print(f"rooms.ts: {len(rooms)} rooms, {len(GLOSS)} signs")
